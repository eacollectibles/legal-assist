/**
 * Paralegals — single source of truth for the licensed paralegals at the firm.
 *
 * Each entry is used wherever a document is generated on behalf of a paralegal
 * (retainers, demand letters, motion records, email signatures, etc.) and
 * drives the auto-populated signature block, printed name, LSO licence
 * number and credential line.
 *
 * For the moment this is a hardcoded list. If the firm grows or you'd rather
 * edit paralegals from the Wix admin without redeploying, this can be moved
 * to a Wix data collection ("paralegals") and loaded async — every consumer
 * already calls through `getActiveParalegals()` / `getParalegalById()` so the
 * change becomes a single-file refactor.
 */

import { EMAIL_PRIMARY, PHONE_DISPLAY } from './contact';

export interface Paralegal {
  /** Stable identifier (use lowercase, kebab-case). */
  id: string;
  /** Full display name as it appears on signed documents. */
  displayName: string;
  /** First name only — useful for greetings, email signatures. */
  firstName: string;
  /** Last name only. */
  lastName: string;
  /** LSO licence number, e.g. "P22020". */
  lsoNumber: string;
  /**
   * Electronic-signature text rendered on signed documents using the legal
   * convention `/s/ <Name>`. Equivalent to a wet signature for the purpose
   * of paralegal-prepared retainers and correspondence.
   */
  electronicSignatureText: string;
  /** Email used as the document author / from-address. */
  email: string;
  /** Phone number shown on the signature block. */
  phone: string;
  /** Credential line under the signature, e.g. "Licensed Paralegal". */
  credentialLine: string;
  /** Whether this paralegal is currently active and selectable in the UI. */
  active: boolean;
}

