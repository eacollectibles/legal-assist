/**
 * Returns all currently-active paralegals, suitable for populating a
 * "Generated by" dropdown on document-generation forms.
 */
export function getActiveParalegals(): Paralegal[] {
  return PARALEGALS.filter((p) => p.active);
}

/**
 * Find a paralegal by id. Returns `undefined` if no match (callers should
 * fall back to a sensible default — usually the firm's primary paralegal).
 */
export function getParalegalById(id: string | null | undefined): Paralegal | undefined {
  if (!id) return undefined;
  return PARALEGALS.find((p) => p.id === id);
}

/**
 * The default paralegal selected when the form first loads (firm primary).
 * Falls back to the first active paralegal in the list if the primary id
 * isn't found.
 */
export const DEFAULT_PARALEGAL_ID = 'jeanfrancois-demers';

export function getDefaultParalegal(): Paralegal {
  return (
    getParalegalById(DEFAULT_PARALEGAL_ID) ||
    getActiveParalegals()[0] ||
    PARALEGALS[0]
  );
}

/**
 * Best-effort match of an authenticated user to one of our paralegals.
 *
 * Used to pre-select the "Generated by" dropdown to whichever paralegal is
 * currently logged in. Matches in this order:
 *   1. Exact email match
 *   2. Display name contains last name
 *   3. Falls back to the firm default
 */
export function resolveLoggedInParalegal(authUser: {
  email?: string | null;
  name?: string | null;
} | null | undefined): Paralegal {
  if (authUser) {
    if (authUser.email) {
      const byEmail = PARALEGALS.find(
        (p) => p.email.toLowerCase() === authUser.email!.toLowerCase()
      );
      if (byEmail) return byEmail;
    }
    if (authUser.name) {
      const lower = authUser.name.toLowerCase();
      const byName = PARALEGALS.find((p) => lower.includes(p.lastName.toLowerCase()));
      if (byName) return byName;
    }
  }
  return getDefaultParalegal();
}
